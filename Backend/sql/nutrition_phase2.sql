-- Výživa (fáza 2): produkty pre čiarový kód a fotku etikety.
-- Predpoklad: sql/nutrition.sql.
--
-- food_products = hodnoty na 100 g.
--   source 'off'      = Open Food Facts, zdieľaná cache pre všetkých,
--                       created_by NULL, zapisuje len BE (service role).
--   source 'label_ai' = prepis etikety cez AI, potvrdený userom,
--   source 'user'     = ručne zadaný produkt.
-- PREČO produkty z etikety vidí len autor: AI aj user sa môžu pomýliť
-- a zlé hodnoty by sa cez zdieľanú cache rozšírili ostatným.
--
-- food_log si hodnoty kopíruje (kcal, makrá) – product_id je len odkaz,
-- zmazanie produktu zápis nezmení (on delete set null).

create table if not exists public.food_products (
  id            bigint generated by default as identity primary key,
  barcode       text check (barcode is null or barcode ~ '^[0-9]{6,14}$'),
  name          text not null check (char_length(name) between 1 and 160),
  brand         text check (brand is null or char_length(brand) <= 120),
  kcal_100g     numeric(7,1) not null check (kcal_100g between 0 and 1000),
  protein_100g  numeric(6,1) check (protein_100g is null or protein_100g between 0 and 100),
  carbs_100g    numeric(6,1) check (carbs_100g is null or carbs_100g between 0 and 100),
  fat_100g      numeric(6,1) check (fat_100g is null or fat_100g between 0 and 100),
  fiber_100g    numeric(6,1) check (fiber_100g is null or fiber_100g between 0 and 100),
  sugar_100g    numeric(6,1) check (sugar_100g is null or sugar_100g between 0 and 100),
  salt_100g     numeric(6,2) check (salt_100g is null or salt_100g between 0 and 100),
  serving_g     numeric(7,1) check (serving_g is null or (serving_g > 0 and serving_g <= 5000)),
  source        text not null check (source in ('off', 'label_ai', 'user')),
  created_by    bigint references public.users(id) on delete cascade,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint food_products_owner check ((source = 'off') = (created_by is null))
);

-- jeden OFF riadok na kód, jeden vlastný produkt na kód a usera
create unique index if not exists food_products_off_barcode_uq
  on public.food_products (barcode) where source = 'off';
create unique index if not exists food_products_user_barcode_uq
  on public.food_products (created_by, barcode) where created_by is not null and barcode is not null;
create index if not exists food_products_barcode_idx
  on public.food_products (barcode);

alter table public.food_products enable row level security;
grant select, insert, update, delete on public.food_products to authenticated;

drop policy if exists select_own_or_off on public.food_products;
drop policy if exists insert_own on public.food_products;
drop policy if exists update_own on public.food_products;
drop policy if exists delete_own on public.food_products;

create policy select_own_or_off on public.food_products
  for select using (source = 'off' or created_by = app_user_id());
create policy insert_own on public.food_products
  for insert with check (created_by = app_user_id() and source <> 'off');
create policy update_own on public.food_products
  for update using (created_by = app_user_id())
  with check (created_by = app_user_id() and source <> 'off');
create policy delete_own on public.food_products
  for delete using (created_by = app_user_id());

-- odkaz zo zápisu jedla na produkt
alter table public.food_log drop constraint if exists food_log_product_fk;
alter table public.food_log
  add constraint food_log_product_fk
  foreign key (product_id) references public.food_products(id) on delete set null;

