-- Výživa (fáza 1): profil výživy, zápis jedla, obľúbené jedlá.
-- Predpoklad: funkcie public.app_user_id() a public.sr_my_athlete_ids()
-- (sql/trainer_read_access.sql) už existujú.
--
-- Ciele (kcal, makrá) sa NEUKLADAJÚ – BE ich počíta pri čítaní
-- (Services/nutrition_targets.py), lebo aktivita zo Stravy príde neskôr
-- a plán sa mení. Váha je v users_metrics (weight_kg), pohlavie, narodenie
-- a výška v profile_static – nič z toho sa tu neduplikuje.
--
-- Všetky tabuľky: user číta a mení len svoje riadky (rovnaké politiky ako
-- users_preferences), aktívny tréner jeho riadky len číta (trainer_read).
-- Mazanie účtu: on delete cascade z public.users.

-- ---------------------------------------------------------------------------
-- Profil výživy = cieľ a súhlas so spracovaním údajov o strave (GDPR).
-- Bez riadku (bez súhlasu) sa nič nepočíta ani nezapisuje.
-- ---------------------------------------------------------------------------
create table if not exists public.nutrition_profile (
  user_id           bigint primary key references public.users(id) on delete cascade,
  goal              text not null default 'maintain'
                      check (goal in ('lose', 'maintain', 'gain')),
  -- % úpravy kcal: chudnutie 10–20, naberanie 5–10, udržiavanie null
  goal_rate_pct     numeric(4,1)
                      check (goal_rate_pct is null or goal_rate_pct between 0 and 20),
  bmr_manual        integer
                      check (bmr_manual is null or bmr_manual between 800 and 4000),
  neat_factor       numeric(3,2) not null default 1.30
                      check (neat_factor between 1.10 and 1.80),
  protein_g_per_kg  numeric(3,2) not null default 1.80
                      check (protein_g_per_kg between 1.60 and 2.20),
  consent_at        timestamptz not null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Zápis jedla. AI výstup sem ide až po potvrdení userom.
-- product_id = fáza 2 (food_products), FK sa doplní s tou tabuľkou.
-- ---------------------------------------------------------------------------
create table if not exists public.food_log (
  id             bigint generated by default as identity primary key,
  user_id        bigint not null references public.users(id) on delete cascade,
  log_date       date   not null,
  meal           text   not null
                   check (meal in ('breakfast', 'lunch', 'dinner', 'snack')),
  product_id     bigint,
  name           text   not null check (char_length(name) between 1 and 120),
  grams          numeric(7,1) check (grams is null or (grams > 0 and grams <= 5000)),
  kcal           numeric(7,1) not null check (kcal between 0 and 10000),
  protein_g      numeric(6,1) not null default 0 check (protein_g between 0 and 1000),
  carbs_g        numeric(6,1) not null default 0 check (carbs_g between 0 and 1000),
  fat_g          numeric(6,1) not null default 0 check (fat_g between 0 and 1000),
  source         text   not null default 'manual'
                   check (source in ('manual', 'text', 'favorite', 'recent', 'barcode', 'label', 'photo')),
  ai_confidence  numeric(3,2) check (ai_confidence is null or ai_confidence between 0 and 1),
  raw_input      text check (raw_input is null or char_length(raw_input) <= 500),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists food_log_user_date_idx
  on public.food_log (user_id, log_date);

-- ---------------------------------------------------------------------------
-- Obľúbené jedlá. Jedno jedlo môže mať viac položiek (rožok + maslo + šunka),
-- items = [{name, grams, kcal, protein_g, carbs_g, fat_g}], súčty vedľa.
-- ---------------------------------------------------------------------------
create table if not exists public.food_favorites (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  name        text   not null check (char_length(name) between 1 and 120),
  meal        text check (meal is null or meal in ('breakfast', 'lunch', 'dinner', 'snack')),
  items       jsonb  not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  kcal        numeric(7,1) not null default 0,
  protein_g   numeric(6,1) not null default 0,
  carbs_g     numeric(6,1) not null default 0,
  fat_g       numeric(6,1) not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists food_favorites_user_idx
  on public.food_favorites (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['nutrition_profile', 'food_log', 'food_favorites']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);

    execute format('drop policy if exists select_own on public.%I', t);
    execute format('drop policy if exists insert_own on public.%I', t);
    execute format('drop policy if exists update_own on public.%I', t);
    execute format('drop policy if exists delete_own on public.%I', t);
    execute format('drop policy if exists trainer_read on public.%I', t);

    execute format(
      'create policy select_own on public.%I for select using (user_id = app_user_id())', t);
    execute format(
      'create policy insert_own on public.%I for insert with check (user_id = app_user_id())', t);
    execute format(
      'create policy update_own on public.%I for update using (user_id = app_user_id()) '
      'with check (user_id = app_user_id())', t);
    execute format(
      'create policy delete_own on public.%I for delete using (user_id = app_user_id())', t);

    -- živý tréner: len čítanie, kým spolupráca beží
    execute format(
      'create policy trainer_read on public.%I for select to authenticated '
      'using (user_id in (select public.sr_my_athlete_ids()))', t);
  end loop;
end $$;

